"""The generated appendconfig: exact text, stable order, and the flags it must state.

The assertions are deliberately literal — this file is read by RetroArch, not by us,
so "it contains the right keys" is weaker than "it says exactly this".
"""

from __future__ import annotations

import pytest

from domain.retroarch_appendconfig import (
    STATE_DIR_NAME,
    appendconfig_dirs,
    appendconfig_name,
    render_appendconfig,
)

BANK = "/home/deck/homebrew/data/romm-tender/saves/gba"
STATES = f"/home/deck/homebrew/data/romm-tender/{STATE_DIR_NAME}/gba"


def _text(**kwargs) -> str:
    return render_appendconfig(save_dir=BANK, state_dir=STATES, **kwargs)


class TestContent:
    def test_the_save_and_state_directories_are_stated(self) -> None:
        text = _text()
        assert f'savefile_directory = "{BANK}"' in text
        assert f'savestate_directory = "{STATES}"' in text

    def test_sorting_is_switched_off_explicitly(self) -> None:
        """The bank is flat; a nested save is one the plugin cannot find."""
        text = _text()
        for key in (
            "sort_savefiles_enable",
            "sort_savefiles_by_content_enable",
            "sort_savestates_enable",
            "sort_savestates_by_content_enable",
        ):
            assert f'{key} = "false"' in text

    def test_saves_beside_the_rom_are_switched_off(self) -> None:
        text = _text()
        assert 'savefiles_in_content_dir = "false"' in text
        assert 'savestates_in_content_dir = "false"' in text

    def test_no_system_directory_unless_one_is_given(self) -> None:
        assert "system_directory" not in _text()

    def test_a_system_directory_is_written_when_resolved(self) -> None:
        assert 'system_directory = "/home/deck/Emulation/bios"' in _text(system_dir="/home/deck/Emulation/bios")

    def test_the_header_says_it_is_generated(self) -> None:
        assert _text().startswith("# Generated by Arcoon Deck")

    def test_every_line_is_a_comment_or_a_setting(self) -> None:
        for line in _text().splitlines():
            assert line == "" or line.startswith("#") or " = " in line


class TestStability:
    def test_the_same_intent_renders_byte_identical_text(self) -> None:
        """The adapter skips a rewrite by comparing text, so this must hold."""
        assert _text() == _text()

    def test_keys_come_in_a_fixed_order(self) -> None:
        keys = [line.split(" = ")[0] for line in _text().splitlines() if " = " in line]
        assert keys == [
            "savefile_directory",
            "savestate_directory",
            "savefiles_in_content_dir",
            "savestates_in_content_dir",
            "sort_savefiles_enable",
            "sort_savefiles_by_content_enable",
            "sort_savestates_enable",
            "sort_savestates_by_content_enable",
            "autosave_interval",
        ]


class TestQuoting:
    def test_a_backslash_is_escaped(self) -> None:
        text = render_appendconfig(save_dir="/saves/a\\b", state_dir="/states")
        assert 'savefile_directory = "/saves/a\\\\b"' in text

    def test_a_quote_is_escaped(self) -> None:
        text = render_appendconfig(save_dir='/saves/a"b', state_dir="/states")
        assert 'savefile_directory = "/saves/a\\"b"' in text

    def test_a_line_break_is_refused(self) -> None:
        """It cannot be represented: it would end the setting and start a new one."""
        with pytest.raises(ValueError, match="line break"):
            render_appendconfig(save_dir="/saves/a\nb", state_dir="/states")


class TestNames:
    def test_one_file_per_platform(self) -> None:
        assert appendconfig_name("gba") == "retroarch-gba.cfg"
        assert appendconfig_name("switch") == "retroarch-switch.cfg"

    def test_dirs_follow_the_bank_layout(self) -> None:
        save_dir, state_dir = appendconfig_dirs(data_dir="/data", layout_subdir=("gba",))
        assert save_dir == "/data/saves/gba"
        assert state_dir == f"/data/{STATE_DIR_NAME}/gba"

    def test_a_multi_level_layout_mirrors_under_states(self) -> None:
        """Switch's unit lives under nand/user/save; the states dir mirrors it."""
        save_dir, state_dir = appendconfig_dirs(
            data_dir="/data",
            layout_subdir=("switch", "nand", "user", "save"),
        )
        assert save_dir == "/data/saves/switch/nand/user/save"
        assert state_dir == f"/data/{STATE_DIR_NAME}/switch/nand/user/save"
